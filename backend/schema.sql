CREATE DATABASE IF NOT EXISTS uber_copiloto CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE uber_copiloto;

CREATE TABLE users (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  email VARCHAR(190) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE driver_settings (
  user_id BIGINT UNSIGNED PRIMARY KEY,
  fuel_price_per_gallon DECIMAL(8,3) NOT NULL DEFAULT 3.000,
  consumption_km_per_liter DECIMAL(8,3) NOT NULL DEFAULT 9.000,
  maintenance_per_km DECIMAL(8,3) NOT NULL DEFAULT 0.100,
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

CREATE TABLE trips (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  user_id BIGINT UNSIGNED NOT NULL,
  platform VARCHAR(30) NOT NULL DEFAULT 'uber',
  fare_received DECIMAL(10,2) NOT NULL,
  pickup_km DECIMAL(8,2) NOT NULL DEFAULT 0,
  passenger_km DECIMAL(8,2) NOT NULL DEFAULT 0,
  duration_minutes DECIMAL(8,2) NOT NULL DEFAULT 0,
  source VARCHAR(30) NOT NULL DEFAULT 'manual',
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);
